import { cssToTailwind } from "../styles/tailwind.js";
import { createNamer, kebabCase } from "../utils/names.js";

const COLOR_RE = /#[0-9a-fA-F]{6}\b|rgba\([^)]*\)/g;

/**
 * Style strategies turn IR css objects into either class names + a stylesheet (plain CSS)
 * or Tailwind utility strings. Both consume the same declarations, so output is consistent.
 */
export function createStyleStrategy(mode, { responsive = true } = {}) {
  return mode === "tailwind" ? tailwindStrategy() : cssStrategy(responsive);
}

const decl = (css) => Object.entries(css).filter(([, v]) => v !== undefined && v !== "").map(([p, v]) => `  ${p}: ${v};`).join("\n");

function cssStrategy() {
  const namer = createNamer();
  const registry = new Map(); // key -> { cls, css, media }
  const order = [];
  const runs = new Map();
  const register = (base, css, media, suffix = "") => {
    const hasStyle = Object.keys(css || {}).length || Object.values(media || {}).some((m) => Object.keys(m).length);
    if (!hasStyle) return "";
    const key = JSON.stringify([css, media]);
    let e = registry.get(key);
    if (!e) {
      const nm = namer((kebabCase(base) || "el") + suffix);
      e = { cls: nm, css, media };
      registry.set(key, e);
      order.push(e);
    }
    return e.cls;
  };
  return {
    mode: "css",
    intrinsic: (node) => register(node.name || node.tag, node.css, node.media),
    place: (node) => register("pos", node.place, node.placeMedia), // shared by every node with identical placement, so it gets a neutral name
    run: (css, hint = "text") => { if (!Object.keys(css).length) return ""; const k = JSON.stringify(css); if (!runs.has(k)) runs.set(k, register(`${hint}-style`, css, {})); return runs.get(k); },
    stylesheet({ resolveAsset, base = true }) {
      // design tokens: colours/fonts used more than once become CSS variables
      const counts = new Map();
      const scan = (s) => { for (const m of String(s).match(COLOR_RE) || []) counts.set(m, (counts.get(m) || 0) + 1); };
      order.forEach((e) => { Object.values(e.css).forEach(scan); Object.values(e.media).forEach((m) => Object.values(m).forEach(scan)); });
      const fonts = new Map();
      order.forEach((e) => { const f = e.css["font-family"]; if (f) fonts.set(f, (fonts.get(f) || 0) + 1); });
      const tokens = [];
      const tokenFor = new Map();
      [...counts].filter(([, n]) => n >= 2).sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)).forEach(([c], i) => {
        const name = `--color-${i + 1}`;
        tokenFor.set(c, `var(${name})`); tokens.push(`  ${name}: ${c};`);
      });
      [...fonts].filter(([, n]) => n >= 1).sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)).forEach(([f], i) => {
        const name = `--font-${i + 1}`;
        tokenFor.set(f, `var(${name})`); tokens.push(`  ${name}: ${f};`);
      });
      const sub = (v) => {
        let s = String(v);
        if (tokenFor.has(s)) return tokenFor.get(s);
        s = s.replace(COLOR_RE, (m) => tokenFor.get(m) || m);
        return resolveAsset(s);
      };
      const mapped = (css) => Object.fromEntries(Object.entries(css).map(([k, v]) => [k, v === undefined ? v : sub(v)]));
      const out = [];
      out.push("/* Generated by Figma2Code — deterministic conversion. Edit freely. */");
      if (tokens.length) out.push(`:root {\n${tokens.join("\n")}\n}`);
      if (base) out.push("*,\n*::before,\n*::after {\n  box-sizing: border-box;\n}\n\nbody {\n  margin: 0;\n  -webkit-font-smoothing: antialiased;\n}\n\nimg {\n  display: block;\n}");
      const mediaRules = [];
      for (const e of order) {
        if (Object.keys(e.css).length) out.push(`.${e.cls} {\n${decl(mapped(e.css))}\n}`);
        for (const [bp, m] of Object.entries(e.media)) if (Object.keys(m).length) mediaRules.push({ bp, rule: `  .${e.cls} {\n${decl(mapped(m)).replace(/^/gm, "  ")}\n  }` });
      }
      if (mediaRules.length) out.push(`@media (max-width: 768px) {\n${mediaRules.map((m) => m.rule).join("\n")}\n}`);
      return out.join("\n\n") + "\n";
    },
  };
}

function tailwindStrategy() {
  const tw = (css, media = {}) => {
    const c = cssToTailwind(css);
    for (const [bp, m] of Object.entries(media)) c.push(...cssToTailwind(m, `max-${bp}:`));
    return c.join(" ");
  };
  return {
    mode: "tailwind",
    intrinsic: (node) => tw(node.css, node.media),
    place: (node) => tw(node.place, node.placeMedia),
    run: (css) => tw(css),
    stylesheet({ base = true }) {
      return `@import "tailwindcss";\n\n/* Generated by Figma2Code — styling lives in Tailwind utility classes. */\n${base ? "body {\n  -webkit-font-smoothing: antialiased;\n}\n" : ""}`;
    },
  };
}
