/** Static project scaffolding (package.json, configs, README) per framework. Versions are pinned to ranges verified to install and build. */
export const VERSIONS = { react: "^19.2.0", next: "^16.0.0", vite: "^7.0.0", pluginReact: "^5.0.0", tailwind: "^4.1.0" };

const pkgJson = (o) => JSON.stringify(o, null, 2) + "\n";

export function packageJson({ framework, styling, name }) {
  const base = { name, version: "0.1.0", private: true };
  const tw = styling === "tailwind";
  if (framework === "nextjs") {
    return pkgJson({ ...base, scripts: { dev: "next dev", build: "next build", start: "next start" },
      dependencies: { next: VERSIONS.next, react: VERSIONS.react, "react-dom": VERSIONS.react },
      ...(tw ? { devDependencies: { tailwindcss: VERSIONS.tailwind, "@tailwindcss/postcss": VERSIONS.tailwind } } : {}) });
  }
  if (framework === "react") {
    return pkgJson({ ...base, type: "module", scripts: { dev: "vite", build: "vite build", preview: "vite preview" },
      dependencies: { react: VERSIONS.react, "react-dom": VERSIONS.react },
      devDependencies: { vite: VERSIONS.vite, "@vitejs/plugin-react": VERSIONS.pluginReact, ...(tw ? { tailwindcss: VERSIONS.tailwind, "@tailwindcss/vite": VERSIONS.tailwind } : {}) } });
  }
  return pkgJson({ ...base, scripts: { start: "npx --yes serve ." } });
}

