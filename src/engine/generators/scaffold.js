export function readme({ framework, styling, name, report, pages }) {
  const run = {
    html: "Open `index.html` in a browser, or run `npm start` to serve the folder locally.",
    react: "```bash\nnpm install\nnpm run dev      # development server\nnpm run build    # production build into dist/\n```",
    nextjs: "```bash\nnpm install\nnpm run dev      # development server\nnpm run build    # production build\nnpm start        # serve the production build\n```",
  }[framework];
  const s = report.summary();
  const lines = [`# ${name}`, "", `Generated by **Figma2Code** using a deterministic Figma-to-code compiler (no AI).`, "",
    `- Framework: ${{ html: "HTML + CSS + JavaScript", react: "React (Vite)", nextjs: "Next.js (App Router)" }[framework]}`,
    `- Styling: ${styling === "tailwind" ? "Tailwind CSS v4" : "Plain CSS with CSS variables"}`,
    `- Pages: ${pages.map((p) => p.name).join(", ")}`, "", "## Getting started", "", run, ""];
  if (framework === "html" && styling === "tailwind") lines.push("Tailwind is loaded in the browser through `@tailwindcss/browser` (a CDN script) so the folder works with no build step. For production, compile with the Tailwind CLI instead.", "");
  if (framework !== "html") lines.push("Fonts are loaded from Google Fonts by family name; replace with self-hosted fonts if a family is not available there.", "");
  lines.push("## Conversion report", "", `- Converted nodes: ${s.converted}`, `- Skipped nodes: ${s.skipped}`, `- Unsupported features: ${s.unsupported}`, `- Approximations: ${s.approximations}`, `- Asset failures: ${s.assetFailures}`, "",
    "Layout is derived from Figma Auto Layout and constraints; where a frame has neither, flow layout is inferred from child geometry and otherwise positioned absolutely. Output is not guaranteed pixel-perfect.", "");
  return lines.join("\n");
}
